/* ---- counts, computed so they can never drift from the data ---- */
function curriculumCount(section){
  var n = 0;
  (section.groups || []).forEach(function(g){ n += g.items.length; });
  if(section.grid)  n += section.grid.rows.length  * section.grid.aspects.length;
  if(section.grid2) n += section.grid2.rows.length * section.grid2.aspects.length;
  return n;
}
